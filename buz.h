#ifndef __BUZ_H
#define __BUZ_H

/***************************************************************
 * 文件名称: buz.h
 * 文件功能: 蜂鸣器驱动模块头文件
 * 适用芯片: SC系列单片机 / 8051兼容内核
 * 编 写 人: cnn
 * 更新时间: 2025-10-25
 ***************************************************************/

/**
 * @brief 蜂鸣器初始化
 * @note  设置蜂鸣器IO口为输出模式并关闭蜂鸣器。
 */
void Buz_Init(void);

/**
 * @brief 蜂鸣器定时处理函数
 * @note  需在定时器中断中每100us调用一次，用于控制蜂鸣器频率与响声间隔。
 */
void Buz_TimerTick(void);

/**
 * @brief 蜂鸣器响一声
 * @note  发出一次固定时长的蜂鸣（约200ms），常用于提示音。
 */
void beep(void);

/**
 * @brief 蜂鸣器响多声
 * @param times 响声次数（例如 2 表示响两声，3 表示响三声）
 * @note  用于状态提示或错误警告等多声提示。
 */
void Beep_Times(unsigned char times);

#endif // __BUZ_H
